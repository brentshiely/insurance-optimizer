#!/usr/bin/env bash
# Regenerates the committed snapshots: every tests/snapshots/gen/<name>.gen.mjs is run (under macOS JavaScriptCore,
# or Node when jsc is missing) and its printed JSON is written to tests/snapshots/<name>.snap.mjs as
# "export default <json>;". Tests compare the same data against those files with assertSnapshot.
#
# Usage:
#   scripts/update-snapshots.sh [name-substring]           rewrite the snapshots (all, or those whose name contains the text)
#   scripts/update-snapshots.sh --check [name-substring]   write nothing; exit 1 and list the snapshots that are out of date
#
# Snapshots change only deliberately: run this, read `git diff tests/snapshots`, and make sure every difference is
# explained by the change you made. See tests/snapshots/README.md.
set -uo pipefail
cd "$(dirname "$0")/.."
JSC="${JSC:-/System/Library/Frameworks/JavaScriptCore.framework/Versions/Current/Helpers/jsc}"

CHECK=0
if [[ "${1:-}" == "--check" ]]; then CHECK=1; shift; fi
FILTER="${1:-}"

if [[ -x "$JSC" ]]; then
  run_gen() { "$JSC" -m "$1" 2>&1; }
elif command -v node >/dev/null 2>&1; then
  run_gen() { node "$1" 2>&1; }
else
  echo "No JavaScript runtime found (need macOS jsc or node)" >&2; exit 2
fi

TMP="$(mktemp tests/snapshots/.update.XXXXXX)"
trap 'rm -f "$TMP"' EXIT

found=0; stale=0; failed=0
for gen in tests/snapshots/gen/*.gen.mjs; do
  [[ -e "$gen" ]] || continue
  name="$(basename "$gen" .gen.mjs)"
  [[ -n "$FILTER" && "$name" != *"$FILTER"* ]] && continue
  found=$((found + 1))
  out="tests/snapshots/$name.snap.mjs"

  json="$(run_gen "$gen")"; code=$?
  if [[ $code -ne 0 || -z "$json" || ( "${json:0:1}" != "{" && "${json:0:1}" != "[" ) ]]; then
    echo "FAILED  $name: the generator did not print JSON (exit $code)" >&2
    echo "$json" | head -20 >&2
    failed=$((failed + 1)); continue
  fi
  {
    printf '%s\n' "// Generated by scripts/update-snapshots.sh from tests/snapshots/gen/$name.gen.mjs. Do not edit by hand."
    printf '%s\n' "export default $json;"
  } > "$TMP"

  if [[ $CHECK -eq 1 ]]; then
    if cmp -s "$TMP" "$out"; then echo "ok      $name"; else echo "STALE   $name"; stale=$((stale + 1)); fi
  elif [[ -e "$out" ]] && cmp -s "$TMP" "$out"; then
    echo "same    $name"
  else
    mv "$TMP" "$out"
    chmod 644 "$out"
    TMP="$(mktemp tests/snapshots/.update.XXXXXX)"
    echo "wrote   $name -> $out"
  fi
done

if [[ $found -eq 0 ]]; then echo "No generator matched${FILTER:+ \"$FILTER\"} in tests/snapshots/gen/" >&2; exit 2; fi
if [[ $failed -gt 0 ]]; then exit 1; fi
if [[ $CHECK -eq 1 && $stale -gt 0 ]]; then echo "$stale snapshot(s) out of date: run scripts/update-snapshots.sh" >&2; exit 1; fi
exit 0
